"""Download every NBS price watch file and extract the spreadsheets.

Source archives land in raw/<series>/ and the spreadsheets inside them are
extracted to extracted/<series>/, which is what the parsers read. Both
folders are gitignored and regenerated by this script.
"""
import re, shutil, sys, time, urllib.request, urllib.parse, zipfile
from pathlib import Path

BASE = "https://microdata.nigerianstat.gov.ng"
SERIES = {"pms": 157, "ago": 158, "nhk": 159, "lpg": 160, "food": 162, "cohd": 146}
ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "raw"
EXTRACTED = ROOT / "extracted"
UA = {"User-Agent": "portfolio-research/1.0"}


def fetch(url, tries=3):
    for i in range(tries):
        try:
            return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=90).read()
        except Exception as e:
            if i == tries - 1:
                raise
            time.sleep(3)


def links_for(cid):
    html = fetch(f"{BASE}/index.php/catalog/{cid}").decode("utf-8", "ignore")
    found = re.findall(r'href="([^"]*?/catalog/\d+/download/\d+[^"]*)"', html)
    out = []
    for l in dict.fromkeys(found):
        if l.lower().endswith(".pdf"):
            continue
        out.append(l if l.startswith("http") else BASE + l)
    return out


def main():
    total = 0
    for name, cid in SERIES.items():
        d = RAW / name
        d.mkdir(parents=True, exist_ok=True)
        urls = links_for(cid)
        print(f"{name}: {len(urls)} files")
        for u in urls:
            fn = urllib.parse.unquote(u.rsplit("/", 1)[-1]).replace(" ", "_")
            target = d / fn
            if target.exists() and target.stat().st_size > 0:
                continue
            try:
                target.write_bytes(fetch(u))
                total += 1
                print(f"   {fn}  {target.stat().st_size//1024}KB")
            except Exception as e:
                print(f"   FAILED {fn}: {e}", file=sys.stderr)
    print(f"\ndownloaded {total} new files")
    extract()


def extract():
    """Copy loose spreadsheets and unpack the ones inside archives."""
    for series in SERIES:
        src, dest = RAW / series, EXTRACTED / series
        if not src.exists():
            continue
        dest.mkdir(parents=True, exist_ok=True)
        n = 0
        for f in sorted(src.iterdir()):
            if f.suffix.lower() == ".xlsx":
                shutil.copy(f, dest / f.name)
                n += 1
            elif f.suffix.lower() == ".zip":
                try:
                    with zipfile.ZipFile(f) as z:
                        for member in z.namelist():
                            if member.startswith("__MACOSX"):
                                continue
                            if member.lower().endswith((".xlsx", ".xls")):
                                name = f.stem + "__" + Path(member).name.replace(" ", "_")
                                (dest / name).write_bytes(z.read(member))
                                n += 1
                except zipfile.BadZipFile:
                    print(f"   unreadable archive: {f.name}", file=sys.stderr)
        print(f"{series}: {n} spreadsheets extracted")


if __name__ == "__main__":
    main()
